/** 政策ID → 所属ライフイベントIDの配列（キャッシュ） */
const _policyToEventsCache: Record<string, string[]> = {};
(function buildReverseMap() {
  for (const [eventId, policyIds] of Object.entries(LIFE_EVENT_POLICY_MAP)) {
    for (const pid of policyIds) {
      if (!_policyToEventsCache[pid]) _policyToEventsCache[pid] = [];
      _policyToEventsCache[pid].push(eventId);
    }
  }
})();

/** 政策IDからその政策が属するライフイベントを取得 */
export function getLifeEventsForPolicy(policyId: string): LifeEvent[] {
  const eventIds = _policyToEventsCache[policyId] || [];
  return LIFE_EVENTS.filter(e => eventIds.includes(e.id));
}

/** ライフイベントIDから該当する政策データを取得 */
export function getPoliciesForLifeEvent(eventId: string): PolicyTopic[] {
  const policyIds = LIFE_EVENT_POLICY_MAP[eventId] || [];
  const idSet = new Set(policyIds);
  return getAllPolicies().filter(p => idSet.has(p.id));
}

/** 全ライフイベント一覧を取得 */
export function getAllLifeEvents(): LifeEvent[] {
  return LIFE_EVENTS;
}
